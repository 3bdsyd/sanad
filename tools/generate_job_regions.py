#!/usr/bin/env python3
"""Generate the offline first-level administrative catalog from its snapshot."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'server/job_regions.json').read_text())

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

rows = ['// Generated by tools/generate_job_regions.py; do not edit manually.',
        '// ISO/CLDR notices: assets/licenses/job-regions.txt.',
        'const jobRegionData = <String, List<List<String>>>{']
for country, regions in sorted(data['regions'].items()):
    rows.append(f'  {dart(country)}: [')
    for region in regions:
        values = [region[k] for k in ['code', 'name', 'englishName', 'isoName']]
        rows.append(f'    [{", ".join(map(dart, values))}],')
    rows.append('  ],')
rows += ['};', '']
(root / 'lib/features/jobs/domain/job_regions_data.dart').write_text('\n'.join(rows))
