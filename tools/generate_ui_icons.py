"""Generate the original Sanad action icon family from a single vector source.

Source: assets/icons/fursa-symbols.json (24-unit geometry, no downloaded assets).
Outputs: Dart paths, UIKit CGPaths, and a standalone SVG review sheet.
Run: python3 tools/generate_ui_icons.py
Then: dart format lib/core/fursa_icon_paths.dart
The technical Fursa filenames/API remain stable for existing callers.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'assets/icons/fursa-symbols.json').read_text())
PATHS = DATA['paths']
ACCENTS = DATA.get('accents', {})
STROKE = DATA['strokeWidth']
ALPHA = DATA.get('accentOpacity', 0.12)
COUNTS = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'Q': 4, 'Z': 0}


def commands(source):
    """Reject malformed geometry instead of producing a partially drawn icon."""
    tokens = re.findall(r'[MLHVQCZ]|-?\d+(?:\.\d+)?', source)
    assert re.sub(r'[\s,]', '', source) == ''.join(tokens), source
    index = 0
    while index < len(tokens):
        command = tokens[index]
        assert command in COUNTS, source
        count = COUNTS[command]
        values = tokens[index + 1:index + 1 + count]
        assert len(values) == count, source
        assert all(0 <= float(value) <= 24 for value in values), source
        yield command, values
        index += count + 1


for source in [*PATHS.values(), *ACCENTS.values()]:
    list(commands(source))
assert set(ACCENTS) <= set(PATHS)


def dart_map(name, values):
    return (f'const {name} = <String, String>{{\n' +
            ''.join(f"  '{key}': '{value}',\n" for key, value in values.items()) +
            '};\n')


dart = '// Generated by tools/generate_ui_icons.py. Edit the JSON source.\n\n'
dart += f'const fursaIconStrokeWidth = {STROKE};\n'
dart += f'const fursaIconAccentOpacity = {ALPHA};\n\n'
dart += dart_map('fursaIconPaths', PATHS) + '\n'
dart += dart_map('fursaIconAccents', ACCENTS)
(ROOT / 'lib/core/fursa_icon_paths.dart').write_text(dart)


def cgpath(source):
    result = []
    x = y = start_x = start_y = '0'
    for command, values in commands(source):
        if command == 'M':
            x, y = start_x, start_y = values
            result.append(f'path.move(to: CGPoint(x: {x}, y: {y}))')
        elif command in ('L', 'H', 'V'):
            if command == 'L':
                x, y = values
            elif command == 'H':
                x, = values
            else:
                y, = values
            result.append(f'path.addLine(to: CGPoint(x: {x}, y: {y}))')
        elif command == 'C':
            x1, y1, x2, y2, x, y = values
            result.append(f'path.addCurve(to: CGPoint(x: {x}, y: {y}), '
                          f'control1: CGPoint(x: {x1}, y: {y1}), '
                          f'control2: CGPoint(x: {x2}, y: {y2}))')
        elif command == 'Q':
            x1, y1, x, y = values
            result.append(f'path.addQuadCurve(to: CGPoint(x: {x}, y: {y}), '
                          f'control: CGPoint(x: {x1}, y: {y1}))')
        elif command == 'Z':
            result.append('path.closeSubpath()')
            x, y = start_x, start_y
    return result


def swift_method(name, paths):
    if not paths:
        return (f'  static func {name}(for name: String) -> CGPath? {{\n'
                '    return nil\n'
                '  }')
    lines = [f'  static func {name}(for name: String) -> CGPath? {{',
             '    let path = CGMutablePath()', '    switch name {']
    for key, value in paths.items():
        alias = '"home", "house"' if key == 'home' else f'"{key}"'
        lines.append(f'    case {alias}:')
        lines.extend('      ' + operation for operation in cgpath(value))
    lines += ['    default:', '      return nil', '    }',
              '    return path', '  }']
    return '\n'.join(lines)


swift = ('// Generated by tools/generate_ui_icons.py. Edit the JSON source.\n'
         '// Geometry is identical to the Flutter action icons.\n'
         'import CoreGraphics\n\n'
         'enum FursaIconCatalog {\n'
         f'  static let strokeWidth: CGFloat = {STROKE}\n'
         f'  static let accentOpacity: CGFloat = {ALPHA}\n\n')
swift += swift_method('path', PATHS) + '\n\n'
swift += swift_method('accent', ACCENTS) + '\n}\n'
(ROOT / 'ios/Runner/FursaIconCatalog.swift').write_text(swift)

columns, cell_width, cell_height, top, margin = 6, 152, 112, 120, 24
width = columns * cell_width + margin * 2
height = ((len(PATHS) + columns - 1) // columns) * cell_height + top + 32
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="Sanad original action icon catalog">',
       '<rect width="100%" height="100%" fill="#F2F7FC"/>',
       '<text x="28" y="49" font-family="-apple-system,Arial,sans-serif" font-size="28" font-weight="700" fill="#12233F">SANAD / SOFT LINE</text>',
       f'<text x="28" y="80" font-family="-apple-system,Arial,sans-serif" font-size="14" fill="#577395">{len(PATHS)} original vectors · 24-unit grid · {STROKE} rounded stroke · shared Flutter + UIKit geometry</text>',
       '<circle cx="865" cy="45" r="12" fill="#20508A"/><circle cx="902" cy="45" r="12" fill="#9CC9FA"/>']
for index, (name, source) in enumerate(PATHS.items()):
    x = margin + index % columns * cell_width
    y = top + index // columns * cell_height
    svg.append(f'<rect x="{x}" y="{y}" width="140" height="100" rx="22" fill="white" stroke="#DCE8F5"/>')
    for translate_x, translate_y, scale in [(x + 29, y + 16, 1.6), (x + 98, y + 29, 0.75)]:
        svg.append(f'<g transform="translate({translate_x} {translate_y}) scale({scale})">')
        if name in ACCENTS:
            svg.append(f'<path d="{ACCENTS[name]}" fill="#20508A" opacity="{ALPHA}"/>')
        svg.append(f'<path d="{source}" fill="none" stroke="#20508A" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/></g>')
    svg.append(f'<text x="{x + 70}" y="{y + 82}" text-anchor="middle" font-family="-apple-system,Arial,sans-serif" font-size="11" fill="#12233F">{html.escape(name)}</text>')
svg.append('</svg>')
contact_sheet = '\n'.join(svg)
(ROOT / 'assets/icons/fursa-symbols.svg').write_text(contact_sheet)
preview = ROOT / 'docs/screenshots/sanad-icon-system.svg'
preview.parent.mkdir(parents=True, exist_ok=True)
preview.write_text(contact_sheet)
print(f'Generated {len(PATHS)} Sanad paths + {len(ACCENTS)} supporting accents for Dart/UIKit.')
print(f'Contact sheet: {preview.relative_to(ROOT)}')
