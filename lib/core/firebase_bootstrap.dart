import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

import '../firebase_options.dart';

enum FirebaseConnectionState { unconfigured, unsupported, ready, failed }

/// SDK initialization status, not proof of a working database or push service.
class FirebaseConnection {
  const FirebaseConnection(this.state, {this.projectId, this.errorCode});

  final FirebaseConnectionState state;
  final String? projectId;
  final String? errorCode;

  bool get isReady => state == FirebaseConnectionState.ready;
}

/// Initializes only the mobile Firebase Core SDK. Jobs still use their REST API.
///
/// Uses the real project options generated by FlutterFire. An initialization
/// failure does not prevent browsing the independent jobs REST service.
abstract final class FirebaseBootstrap {
  static FirebaseConnection connection = const FirebaseConnection(
    FirebaseConnectionState.unconfigured,
  );
  static Future<FirebaseConnection>? _initialization;

  static bool get supportsCurrentPlatform =>
      !kIsWeb &&
      (defaultTargetPlatform == TargetPlatform.iOS ||
          defaultTargetPlatform == TargetPlatform.android);

  static Future<FirebaseConnection> initialize({FirebaseOptions? options}) {
    if (!supportsCurrentPlatform) {
      connection = const FirebaseConnection(
        FirebaseConnectionState.unsupported,
      );
      return Future.value(connection);
    }
    return _initialization ??= _initialize(options);
  }

  static Future<FirebaseConnection> _initialize(
    FirebaseOptions? options,
  ) async {
    try {
      final app = await Firebase.initializeApp(
        options: options ?? DefaultFirebaseOptions.currentPlatform,
      );
      connection = FirebaseConnection(
        FirebaseConnectionState.ready,
        projectId: app.options.projectId,
      );
      if (kDebugMode) {
        debugPrint('Firebase Core initialized: ${app.options.projectId}.');
      }
    } on FirebaseException catch (error) {
      final missing =
          options == null &&
          (error.code == 'not-initialized' || error.code == 'no-app');
      connection = FirebaseConnection(
        missing
            ? FirebaseConnectionState.unconfigured
            : FirebaseConnectionState.failed,
        errorCode: error.code,
      );
    } on PlatformException catch (error) {
      final missing =
          options == null &&
          (error.message?.contains(
                'Failed to load FirebaseOptions from resource',
              ) ??
              false);
      connection = FirebaseConnection(
        missing
            ? FirebaseConnectionState.unconfigured
            : FirebaseConnectionState.failed,
        errorCode: missing ? 'missing-native-options' : error.code,
      );
    } on MissingPluginException {
      connection = const FirebaseConnection(
        FirebaseConnectionState.failed,
        errorCode: 'missing-plugin',
      );
    } catch (_) {
      connection = const FirebaseConnection(
        FirebaseConnectionState.failed,
        errorCode: 'initialization-failed',
      );
    }
    if (kDebugMode && !connection.isReady) {
      // Never log complete SDK exceptions, API keys, or configuration contents.
      debugPrint(
        'Firebase Core ${connection.state.name} '
        '(${connection.errorCode ?? 'no-options'}). '
        'See docs/firebase-setup.md. Browsing remains available.',
      );
    }
    return connection;
  }
}
